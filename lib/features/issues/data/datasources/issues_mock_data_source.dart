abstract class IssuesMockDataSource {
  Future<List<Issue>> getIssues();
  Future<Issue?> getIssueById(String id);
  Future<List<String>> getAllTags();
}

class IssuesMockDataSourceImpl implements IssuesMockDataSource {
  final List<Issue> _issues = _generateMockIssues();

  @override
  Future<List<Issue>> getIssues() async {
    await Future.delayed(const Duration(milliseconds: 300));
    return List.unmodifiable(_issues);
  }

  @override
  Future<Issue?> getIssueById(String id) async {
    await Future.delayed(const Duration(milliseconds: 200));
    try {
      return _issues.firstWhere((i) => i.id == id);
    } catch (_) {
      return null;
    }
  }

  @override
  Future<List<String>> getAllTags() async {
    final tags = <String>{};
    for (final issue in _issues) {
      tags.addAll(issue.tags);
    }
    return tags.toList()..sort();
  }
}

